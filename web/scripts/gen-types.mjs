// Regenerate src/lib/supabase/types.ts from the DEV database schema, then format it.
//   npm run db:types
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const OUT = "src/lib/supabase/types.ts";
const shell = process.platform === "win32";

const gen = spawnSync("node", ["scripts/supabase-dev.mjs", "gen", "types", "--lang", "typescript", "--schema", "public"], {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
  shell,
});
if (gen.status !== 0 || !gen.stdout.includes("export type Database")) {
  console.error("Type generation failed; types.ts was not changed.");
  process.exit(gen.status || 1);
}
writeFileSync(OUT, "// Generated by `npm run db:types` from the dev database. Do not edit by hand.\n" + gen.stdout);

const fmt = spawnSync("npx", ["oxfmt", OUT], { stdio: "inherit", shell });
process.exit(fmt.status ?? 1);
